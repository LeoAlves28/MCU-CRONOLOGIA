$("#search").addEventListener("input",render);
$("#toggleCompleted").addEventListener("click",()=>{hideCompleted=!hideCompleted;$("#toggleCompleted").textContent=hideCompleted?"Mostrar concluídos":"Ocultar concluídos";render()});
