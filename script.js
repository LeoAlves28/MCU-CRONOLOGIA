function loadScript(src){
 return new Promise((resolve,reject)=>{
    const script=document.createElement("script");
    script.src=src;
    script.onload=resolve;
    script.onerror=()=>reject(new Error("Não foi possível carregar o Firebase. Verifique sua conexão."));
    document.head.appendChild(script);
 });
}
async function initializeFirebase(){
 if(!hasFirebaseConfig())throw new Error("Configure firebase-config.js e o projeto Firebase para ativar o login.");
 if(cloudInitPromise)return cloudInitPromise;
 cloudInitPromise=(async()=>{
    const version="11.6.0",base=`https://www.gstatic.com/firebasejs/${version}`;
    if(!window.firebase?.auth||!window.firebase?.firestore){
       await loadScript(`${base}/firebase-app-compat.js`);
       await loadScript(`${base}/firebase-auth-compat.js`);
       await loadScript(`${base}/firebase-firestore-compat.js`);
    }
    const firebase=window.firebase;
    const app=firebase.apps.length?firebase.app():firebase.initializeApp(window.MCU_FIREBASE_CONFIG);
    auth=app.auth();
    db=app.firestore();
    await auth.setPersistence(firebase.auth.Auth.Persistence.LOCAL);
    auth.onAuthStateChanged(async user=>{
       currentUser=user;
       cloudReady=false;
       $("#accountForm").hidden=!!user;
       $("#logoutButton").hidden=!user;
       $("#accountTitle").textContent=user?"Conta sincronizada":"Sincronize seu progresso";
       if(!user){
          setAccountStatus("Desconectado. O progresso permanece neste navegador.");
          return;
       }
       try{
          await mergeCloudProgress(user);
       }catch(error){
          setAccountStatus(`Não foi possível sincronizar: ${error.message}`,true);
       }
    });
 })();
 return cloudInitPromise;
}
function completedTitles(){
 const validTitles=new Set(items.map(item=>item[1]));
 return Object.keys(saved).filter(title=>saved[title]&&validTitles.has(title));
}
function saveLocalProgress(){localStorage.setItem(key,JSON.stringify(saved));}
async function mergeCloudProgress(user){
 setAccountStatus("Sincronizando seu progresso...");
 const ref=db.collection("users").doc(user.uid);
 const snapshot=await ref.get();
 const remote=snapshot.exists&&Array.isArray(snapshot.data().completed)?snapshot.data().completed:[];
 const merged=new Set([...completedTitles(),...remote]);
 Object.keys(saved).forEach(title=>delete saved[title]);
 const validTitles=new Set(items.map(item=>item[1]));
 merged.forEach(title=>{if(validTitles.has(title))saved[title]=true;});
 saveLocalProgress();
 render();
 cloudReady=true;
 await writeCloudProgress(user);
 setAccountStatus(`Conectado como ${user.email||"sua conta"}. Progresso sincronizado.`);
}
async function writeCloudProgress(user=currentUser){
 if(!user||!db)return;
 await db.collection("users").doc(user.uid).set({
    completed:completedTitles(),
    updatedAt:window.firebase.firestore.FieldValue.serverTimestamp()
 },{merge:true});
}
function queueCloudSave(){
 if(!currentUser||!cloudReady)return;
 clearTimeout(cloudSaveTimer);
 setAccountStatus("Salvando alterações na nuvem...");
 cloudSaveTimer=setTimeout(()=>{
    const user=currentUser;
    const snapshot=completedTitles();
    cloudWriteQueue=cloudWriteQueue.catch(()=>{}).then(()=>db.collection("users").doc(user.uid).set({
       completed:snapshot,
       updatedAt:window.firebase.firestore.FieldValue.serverTimestamp()
    },{merge:true})).then(()=>{
       if(currentUser?.uid===user.uid)setAccountStatus(`Conectado como ${user.email||"sua conta"}. Progresso sincronizado.`);
    }).catch(error=>setAccountStatus(`Falha ao sincronizar: ${error.message}`,true));
 },400);
}
function accountError(error){
 const messages={
    "auth/email-already-in-use":"Este e-mail já possui uma conta.",
    "auth/invalid-email":"O e-mail informado não é válido.",
    "auth/weak-password":"A senha precisa ter pelo menos 6 caracteres.",
    "auth/invalid-credential":"E-mail ou senha incorretos.",
    "auth/network-request-failed":"Sem conexão. Tente novamente."
 };
 return messages[error.code]||error.message||"Ocorreu um erro ao acessar a conta.";
}
